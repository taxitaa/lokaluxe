create table if not exists public.profiles (
  id uuid primary key references auth.users (id) on delete cascade,
  email text not null,
  full_name text not null default '',
  currency text not null default 'IDR (Rupiah Indonesia)',
  created_at timestamptz not null default now()
);

alter table public.profiles enable row level security;

grant select, insert, update on public.profiles to authenticated;

drop policy if exists "Users can view their own profile" on public.profiles;
create policy "Users can view their own profile"
  on public.profiles for select
  to authenticated
  using ((select auth.uid()) = id);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles for insert
  to authenticated
  with check ((select auth.uid()) = id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update
  to authenticated
  using ((select auth.uid()) = id)
  with check ((select auth.uid()) = id);

create or replace function public.create_profile_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (id, email, full_name)
  values (
    new.id,
    new.email,
    coalesce(new.raw_user_meta_data ->> 'full_name', '')
  )
  on conflict (id) do update
    set email = excluded.email,
        full_name = case
          when public.profiles.full_name = '' then excluded.full_name
          else public.profiles.full_name
        end;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.create_profile_for_new_user();

create table if not exists public.vouchers (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  code text not null unique
    check (code ~ '^LOKA-[A-Z0-9]{6}$'),
  title text not null,
  discount text not null,
  is_used boolean not null default false,
  created_at timestamptz not null default now()
);

alter table public.vouchers enable row level security;

revoke all on public.vouchers from anon, authenticated;
grant select (id, user_id, code, title, discount, is_used, created_at)
  on public.vouchers to authenticated;
grant insert (user_id, code, title, discount, is_used)
  on public.vouchers to authenticated;
grant update (is_used) on public.vouchers to authenticated;
grant usage, select on sequence public.vouchers_id_seq to authenticated;

drop policy if exists "Users can view their own vouchers" on public.vouchers;
create policy "Users can view their own vouchers"
  on public.vouchers for select
  to authenticated
  using ((select auth.uid()) = user_id);

drop policy if exists "Users can create their own vouchers" on public.vouchers;
create policy "Users can create their own vouchers"
  on public.vouchers for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

drop policy if exists "Users can use their own vouchers" on public.vouchers;
create policy "Users can use their own vouchers"
  on public.vouchers for update
  to authenticated
  using ((select auth.uid()) = user_id and is_used = false)
  with check ((select auth.uid()) = user_id and is_used = true);

create table if not exists public.public_feedback (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users (id) on delete cascade,
  comment text not null check (char_length(trim(comment)) between 1 and 2000),
  created_at timestamptz not null default now()
);

alter table public.public_feedback enable row level security;

revoke all on public.public_feedback from anon, authenticated;
grant select (id, comment, created_at)
  on public.public_feedback to authenticated;
grant insert (user_id, comment)
  on public.public_feedback to authenticated;
grant usage, select on sequence public.public_feedback_id_seq to authenticated;

drop policy if exists "Authenticated users can view community feedback"
  on public.public_feedback;
create policy "Authenticated users can view community feedback"
  on public.public_feedback for select
  to authenticated
  using (true);

drop policy if exists "Users can submit their own feedback"
  on public.public_feedback;
create policy "Users can submit their own feedback"
  on public.public_feedback for insert
  to authenticated
  with check ((select auth.uid()) = user_id);
